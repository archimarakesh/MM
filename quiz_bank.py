# «Всё подряд» — тема-микс: вопросы собираются из всех остальных
MIXED_KEY = "mixed"
MIXED_TITLE = "Всё подряд"
MIXED_EMOJI = "🎲"


def theme_keys() -> list:
    return list(THEMES.keys()) + [MIXED_KEY]


def theme_meta(key: str) -> tuple:
    if key == MIXED_KEY:
        return MIXED_TITLE, MIXED_EMOJI
    t = THEMES.get(key, {})
    return t.get("title", key), t.get("emoji", "❓")


def theme_questions(key: str) -> list:
    """Все вопросы темы: [(вопрос, правильный, [обманки])]. Для микса — из всех тем."""
    if key == MIXED_KEY:
        return [q for t in THEMES.values() for q in t["questions"]]
    return list(THEMES.get(key, {}).get("questions", []))


def qhash(question: str) -> str:
    """Стабильный короткий id вопроса (для учёта «уже задавали»)."""
    return hashlib.md5(question.strip().encode("utf-8")).hexdigest()[:12]


def build_options(correct: str, distractors: list, rnd) -> tuple:
    """Собирает варианты для опроса: правильный + обманки, перемешивает.
    Возвращает (список_вариантов, индекс_правильного). Варианты режем до 100 симв."""
    opts = [correct] + list(distractors)
    rnd.shuffle(opts)
    opts = [str(o)[:100] for o in opts]
    return opts, opts.index(str(correct)[:100])
