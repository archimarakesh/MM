# «Всё подряд» — тема-микс: вопросы собираются из всех остальных
MIXED_KEY = "mixed"
MIXED_TITLE = "Всё подряд"
MIXED_EMOJI = "🎲"


def theme_keys() -> list:
    return list(THEMES.keys()) + [MIXED_KEY]


def theme_meta(key: str) -> tuple:
    if key == MIXED_KEY:
        return MIXED_TITLE, MIXED_EMOJI
    t = THEMES.get(key, {})
    return t.get("title", key), t.get("emoji", "❓")


def pick_questions(key: str, n: int, rnd) -> list:
    """n случайных вопросов темы (или из всех для микса). rnd — random.Random."""
    if key == MIXED_KEY:
        pool = [q for t in THEMES.values() for q in t["questions"]]
    else:
        pool = list(THEMES.get(key, {}).get("questions", []))
    rnd.shuffle(pool)
    return pool[:max(1, n)]


def normalize(s: str) -> str:
    """Приводим ответ к каноничному виду для сравнения."""
    s = unicodedata.normalize("NFKC", str(s or "")).lower().strip()
    s = s.replace("ё", "е")
    s = re.sub(r"[^\w\s.,]", " ", s, flags=re.UNICODE)   # убираем пунктуацию, кроме . ,
    s = re.sub(r"\s+", " ", s).strip()
    return s


def is_correct(text: str, answers: list) -> bool:
    """Ответ засчитан, если нормализованный текст совпал с одним из вариантов.
    Для коротких ответов — точное совпадение; для длинных допускаем вхождение."""
    t = normalize(text)
    if not t:
        return False
    for a in answers:
        na = normalize(a)
        if not na:
            continue
        if t == na:
            return True
        # длинный ответ («юрий гагарин») можно написать в предложении
        if len(na) >= 5 and re.search(r"(?<!\w)" + re.escape(na) + r"(?!\w)", t):
            return True
    return False
