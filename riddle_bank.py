def normalize(s: str) -> str:
    """Приводит текст к сравнению: нижний регистр, ё→е, только буквы/цифры и пробелы."""
    s = (s or "").lower().replace("ё", "е")
    out = []
    for ch in s:
        if ch.isalnum() or ch == " ":
            out.append(ch)
        else:
            out.append(" ")
    return " ".join("".join(out).split())


def matches(message: str, answers) -> bool:
    """True, если в сообщении есть принятый ответ как отдельное слово/фраза.
    «Мне кажется, это эхо» засчитает «эхо», но «эхолот» — нет."""
    m = " " + normalize(message) + " "
    for a in answers:
        na = normalize(a)
        if na and (" " + na + " ") in m:
            return True
    return False


def rid(text: str) -> str:
    """Стабильный короткий id загадки (для учёта «уже задавали»)."""
    return hashlib.md5(text.strip().encode("utf-8")).hexdigest()[:12]


def count() -> int:
    return len(RIDDLES)
